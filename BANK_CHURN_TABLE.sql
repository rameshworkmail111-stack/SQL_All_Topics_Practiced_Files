SELECT * FROM BANK_CUSTOMER_DETAILS;

SELECT * FROM BANK_CUSTOMER_DETAILS 
WHERE GEOGRAPHY = "FRANCE" ORDER BY SURNAME ASC,AGE DESC, BALANCE ASC;

SELECT * FROM BANK_CUSTOMER_DETAILS 
WHERE SURNAME LIKE "B%" AND AGE > 40 AND GEOGRAPHY = "FRANCE"; 

SELECT GEOGRAPHY, SUM(BALANCE) FROM BANK_CUSTOMER_DETAILS GROUP BY GEOGRAPHY;

SELECT GEOGRAPHY, gender, SUM(BALANCE) FROM BANK_CUSTOMER_DETAILS GROUP BY GEOGRAPHY, gender;

SELECT * FROM BANK_CUSTOMER_DETAILS WHERE AGE IN (41,61,18);
